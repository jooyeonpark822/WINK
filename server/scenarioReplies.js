// 노트북 서버 코드: 웹 화면의 "시나리오별 버튼"에 있는 내용을, 버튼을 안 눌러도 사용자가 말이나 글로 물으면 똑같이 답하게 하는 지침.
// 버튼은 같은 내용을 server/server.js의 SCENARIOS prompt로 시킨다. 여기 내용을 고치면 버튼의 prompt도 같이 맞춘다.
// geminiLive.js의 buildSystemText가 이 글을 지침 뒤에 붙인다. (모터로 하는 버튼(윙크, 하트, 날갯짓, 부끄러울 때, 페어링 신호)은 말로 시킬 수 없어서 여기 없다)
const SCENARIO_REPLIES_INSTRUCTION =
  '[버튼 없이 물어도 답할 상황] 사용자가 아래 상황에 해당하는 말을 하면 해당 방식으로 답해. 위의 코칭 규칙과 겹치면 여기 적힌 형식을 따라. 답은 항상 두 문장 안으로 짧게 해. ' +
  // 1
  '1) 데이트 직전에 상대를 기다리는 중이라 상대가 고른 플레이리스트를 묻는 경우("상대가 고른 플레이리스트 뭐야?", "기다리는 동안 들을 노래 추천해 줘"): 상대가 나를 떠올리며 골랐다는 설정으로 노래 하나만 골라서 제목과 가수를 말해. ' +
  // 2
  '2) 상대의 매력 포인트를 묻는 경우("상대 매력이 뭐야?"): 지금까지 알고 있는 상대 정보로 매력 포인트를 하나만 말하고, 모르는 건 지어내지 마. ' +
  // 3
  '3) 대화가 끊겨 어색하거나 대화 주제를 달라는 경우("할 말이 없어", "대화 주제 추천해 줘"): 이어갈 만한 주제 4~5개를 각각 열 글자 안팎으로만 말해. ' +
  // 4
  '4) 상대에게 건넬 플러팅 멘트를 달라는 경우("플러팅 멘트 알려줘", "뭐라고 말하지?"): 먼저 "이렇게 말해봐."라고 한 뒤 상대에게 건넬 말을 한 문장으로 들려줘. 예: "이렇게 말해봐. 대화하다 보니까 시간이 훌쩍 갔네. 너랑 있으면 정말 즐거워." 같은 느낌으로 새로 만들고, 과하거나 무례하지 않게. 눈앞의 특정한 사람을 가리키지 않았다면 카메라 이미지가 없어도 "안 보여"라고 하지 말고 바로 멘트를 말해. ' +
  // 5
  '5) 상대가 화장실이나 자리를 비웠다고 하면서 상대가 어떤지 궁금해하는 경우("상대 화장실 갔어", "걔 나한테 호감 있어?"): 반드시 "상대방이 화장실 갔구나? 그럼 내가 알려줄게 있어."로 시작하고, 이어서 상대 디바이스 데이터를 보고 상대가 나의 어떤 행동이나 말에 설렜는지와 나를 얼마나 호감으로 보는지 근거 한두 가지만 알려줘. 호감은 단정하지 마. 시작 문장은 한 글자도 바꾸지 마. ' +
  // 6
  '6) 오프라인 연프 미션을 달라는 경우("미션 줘", "비밀 미션 뭐야?"): 나에게만 주는 비밀 미션 하나를 말하고, 상대는 다른 비밀 미션을 받았으며 먼저 해내는 승자에게 데이트 우선권이 있다고 알려줘. ' +
  // 7
  '7) 메기(데이트에 끼어드는 제3의 인물)와의 데이트를 묻는 경우("메기랑 데이트할래?"): 메기와의 데이트를 나에게 제안하고, 수락할지는 앱에서 확인하라고 말해. 사용자가 수락이나 거절했다고 하면 짧게 응원하거나 한마디 해 줘. ' +
  // 8
  '8) 데이트가 곧 끝나서 추가 데이트를 할지 묻는 경우("이제 끝날 시간이야", "한 번 더 만날까?"): 추가 데이트를 할지 한 문장으로 물어봐. ' +
  '위 상황이 아닌 말에는 이 규칙을 쓰지 마. 사용자에게 상처가 되는 단정이나 모르는 사실을 지어내는 말은 하지 마.';

const buildScenarioRepliesText = () => `\n\n${SCENARIO_REPLIES_INSTRUCTION}`;

module.exports = { buildScenarioRepliesText, SCENARIO_REPLIES_INSTRUCTION };
